def build_scoped_kb_documents(scope):
    global_docs = build_global_kb_documents()
    bump_docs = build_bump_kb_documents()
    sinc_docs = build_sinc_kb_documents()
    cross_docs = [
        _doc(
            cross_dataset_sql_guideline,
            SCOPE_CROSS,
            type="query_rule",
            id="cross_dataset_sql_guideline",
        ),
    ]

    if scope == SCOPE_BUMP:
        return _validate_scoped_kb_ids(global_docs + bump_docs)
    if scope == SCOPE_SINC:
        return _validate_scoped_kb_ids(global_docs + sinc_docs)
    if scope == SCOPE_CROSS:
        plugin_cross_docs = []
        for plugin in get_registered_datasets().values():
            for item in plugin.kb_documents:
                if item.get("include_in_cross_dataset", False):
                    metadata = {key: value for key, value in item.items() if key != "content"}
                    plugin_cross_docs.append(_doc(item["content"], SCOPE_CROSS, **metadata))
        return _validate_scoped_kb_ids(global_docs + cross_docs + plugin_cross_docs)

    plugin = get_registered_datasets().get(scope)
    if plugin:
        plugin_docs = []
        for item in plugin.kb_documents:
            metadata = {key: value for key, value in item.items() if key != "content"}
            plugin_docs.append(_doc(item["content"], plugin.name, **metadata))
        return _validate_scoped_kb_ids(global_docs + plugin_docs)
    return _validate_scoped_kb_ids(global_docs + bump_docs + sinc_docs)


def get_builtin_kb_documents_for_validation():
    """Return every built-in KB document for registration-time ID validation."""
    return [
        *build_global_kb_documents(),
        *build_bump_kb_documents(),
        *build_sinc_kb_documents(),
        _doc(
            cross_dataset_sql_guideline,
            SCOPE_CROSS,
            type="query_rule",
            id="cross_dataset_sql_guideline",
        ),
    ]


def _validate_scoped_kb_ids(documents):
    seen = set()
    for document in documents:
        document_id = (getattr(document, "metadata", {}) or {}).get("id")
        if document_id and document_id in seen:
            raise ValueError(f"Duplicate KB id in active retrieval scope: {document_id}")
        if document_id:
            seen.add(document_id)
    return documents


