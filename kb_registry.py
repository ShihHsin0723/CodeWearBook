def _doc(page_content, dataset_scope, **metadata):
    merged_metadata = {"dataset_scope": dataset_scope, **metadata}
    return Document(page_content=page_content, metadata=merged_metadata)


def _frequency_doc(
    dataset_scope,
    table,
    measure_column,
    frequency_label,
    *,
    frequency_minutes=None,
    level="array",
    data_domain="general",
    confidence="explicit",
    notes="",
):
    measure_name = measure_column or "row-level records"
    lines = [
        "Frequency catalog entry",
        f"table: {table}",
        f"measure: {measure_name}",
        f"level: {level}",
        f"data_domain: {data_domain}",
        f"frequency: {frequency_label}",
        f"confidence: {confidence}",
    ]
    if frequency_minutes is not None:
        lines.append(f"frequency_minutes: {frequency_minutes}")
    if notes:
        lines.append(f"notes: {notes}")

    return _doc(
        "\n".join(lines),
        dataset_scope,
        type="frequency_catalog",
        id=f"frequency::{table}::{measure_column or '__row__'}",
        table=table,
        measure_column=measure_column or "",
        frequency_label=frequency_label,
        frequency_minutes=frequency_minutes,
        frequency_level=level,
        data_domain=data_domain,
        confidence=confidence,
        notes=notes,
    )


def _survey_frequency_doc(
    dataset_scope,
    table,
    survey_title,
    frequency_label,
    *,
    frequency_minutes=None,
    notes="",
    confidence="explicit",
):
    return _frequency_doc(
        dataset_scope,
        table,
        survey_title,
        frequency_label,
        frequency_minutes=frequency_minutes,
        level="row",
        data_domain="survey",
        confidence=confidence,
        notes=notes,
    )


def _row_frequency_doc(
    dataset_scope,
    table,
    frequency_label,
    *,
    frequency_minutes=None,
    data_domain="general",
    confidence="explicit",
    notes="",
):
    return _frequency_doc(
        dataset_scope,
        table,
        "",
        frequency_label,
        frequency_minutes=frequency_minutes,
        level="row",
        data_domain=data_domain,
        confidence=confidence,
        notes=notes,
    )


